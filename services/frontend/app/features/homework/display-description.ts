/** Показывает учебные примеры понятным текстом, не изменяя данные в базе. */
const demoExamples: Record<string, string> = {
  'Можно выполнить: ответа пока нет': 'Прочитайте условие и объясните решение.',
  'Работа ожидает проверки преподавателем': 'Выполните задание и покажите ход решения.',
  'Работа возвращена на исправление': 'Решите задачи и объясните ход решения.',
  'Повторная попытка после замечания': 'Выполните упражнения и проверьте свои ответы.',
  'Работа проверена: оценка 4': 'Выполните задание и проверьте решение.',
  'Файлы преподавателя и учеников':
    'Ознакомьтесь с прикреплёнными материалами и выполните задание.',
  'Срок привязан к отменённому уроку': 'Выполните задание. Срок сдачи уточняется.',
};

export function displayHomeworkDescription(description: string): string {
  const match = /^\[ДЕМО\] (.+)\. Прочитайте условие и объясните решение\.$/u.exec(description);
  return match ? (demoExamples[match[1]] ?? description) : description;
}
